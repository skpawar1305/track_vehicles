#!/usr/bin/env python3
"""A stand-in camera that speaks ONLY RTSP Digest with algorithm=SHA-256.

The production PT-NC120D3 substream challenges `WWW-Authenticate: Digest ...
algorithm=SHA-256`, which every FFmpeg-backed reader (OpenCV/PyAV/GStreamer) and
the Android ``RtspSha256Stream`` client must handle itself. This helper serves a
local H.264 file as if it were that camera so the Android port can be exercised
off-LAN:

  * the RTSP control channel always issues a SHA-256 Digest challenge (there is
    no MD5 fallback and an unauthenticated request always gets 401),
  * RTP/H.264 packetization is delegated to ffmpeg (single-NAL / STAP-A / FU-A,
    payload type 96) and the SDP is generated by the same ffmpeg invocation, so
    ``sprop-parameter-sets`` and the wire format match exactly.

Usage:
  python3 tools/fake_rtsp_camera.py \
      --video /tmp/opencode/testvid_android.mp4 \
      --user admin --password secret \
      --host 0.0.0.0 --port 8554 --path /test

Then point the edge/app at ``rtsp://admin:secret@<host>:8554/test``.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import os
import re
import secrets
import socket
import subprocess
import sys
import tempfile
import threading
import time

REALM = "fake-cam"
PAYLOAD_TYPE = 96


def sha256_hex(value: str) -> str:
    return hashlib.sha256(value.encode("iso-8859-1")).hexdigest()


def parse_digest(header: str) -> dict[str, str]:
    fields: dict[str, str] = {}
    for match in re.finditer(r"([A-Za-z][A-Za-z0-9_-]*)\s*=\s*(?:\"((?:\\.|[^\"])*)\"|([^,\s]+))", header):
        raw = match.group(2) if match.group(2) else match.group(3)
        fields[match.group(1).lower()] = raw.replace('\\"', '"').replace("\\\\", "\\")
    return fields


def challenge_header(nonce: str) -> str:
    return (
        f'Digest realm="{REALM}", nonce="{nonce}", algorithm=SHA-256, qop="auth"'
    )


def verify_digest(method: str, uri: str, authorization: str | None, username: str, password: str) -> bool:
    if not authorization or not authorization.lower().startswith("digest "):
        return False
    f = parse_digest(authorization[len("digest "):])
    if f.get("username") != username or f.get("realm") != REALM:
        return False
    if not f.get("algorithm", "").upper().startswith("SHA-256"):
        return False
    if f.get("uri") != uri:
        return False
    ha1 = sha256_hex(f"{username}:{REALM}:{password}")
    ha2 = sha256_hex(f"{method}:{uri}")
    qop = f.get("qop")
    if qop:
        expected = sha256_hex(f"{ha1}:{f.get('nonce','')}:{f.get('nc','')}:{f.get('cnonce','')}:{qop}:{ha2}")
    else:
        expected = sha256_hex(f"{ha1}:{f.get('nonce','')}:{ha2}")
    return secrets.compare_digest(expected, f.get("response", ""))


def build_sdp(video: str) -> str:
    """Ask ffmpeg to emit the SDP for the H.264 copy it would send as RTP."""
    with tempfile.NamedTemporaryFile("r", suffix=".sdp", delete=False) as handle:
        sdp_path = handle.name
    try:
        subprocess.run(
            [
                "ffmpeg", "-v", "error", "-i", video, "-an", "-c:v", "copy",
                "-frames:v", "1", "-f", "rtp", "-payload_type", str(PAYLOAD_TYPE),
                "-sdp_file", sdp_path, "rtp://127.0.0.1:15000",
            ],
            check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            timeout=30,
        )
        with open(sdp_path, "r", encoding="utf-8", errors="replace") as handle:
            sdp = handle.read()
    finally:
        try:
            os.unlink(sdp_path)
        except OSError:
            pass
    # libavformat's SDP omits a=control; the Android client refuses a track with
    # no control URL, and the SETUP target is derived from it.
    if "a=control:" not in sdp:
        sdp = sdp.rstrip("\r\n") + "\na=control:streamid=0\n"
    return sdp


class Session:
    def __init__(self, conn: socket.socket, addr: tuple[str, int], cfg: "Config"):
        self.conn = conn
        self.addr = addr
        self.cfg = cfg
        self.nonce = secrets.token_hex(16)
        self.session_id = secrets.token_hex(6)
        self.client_ip = addr[0]
        self.client_port: int | None = None
        self.sender: subprocess.Popen[bytes] | None = None
        self.closed = False

    # ── RTSP plumbing ────────────────────────────────────────────────────
    def read_request(self) -> tuple[str, str, dict[str, str]] | None:
        buffer = b""
        while b"\r\n\r\n" not in buffer:
            chunk = self.conn.recv(4096)
            if not chunk:
                return None
            buffer += chunk
            if len(buffer) > 1 << 20:
                return None
        head = buffer.split(b"\r\n\r\n", 1)[0].decode("iso-8859-1")
        lines = head.split("\r\n")
        request_line = lines[0].split(" ")
        if len(request_line) < 2:
            return None
        method, uri = request_line[0].upper(), request_line[1]
        headers: dict[str, str] = {}
        for line in lines[1:]:
            key, _, value = line.partition(":")
            if value:
                headers[key.strip().lower()] = value.strip()
        return method, uri, headers

    def respond(self, cseq: str, code: int, reason: str, extra: list[str] | None = None,
                body: bytes | None = None, content_type: str | None = None) -> None:
        lines = [f"RTSP/1.0 {code} {reason}", f"CSeq: {cseq}"]
        if body is not None:
            if content_type:
                lines.append(f"Content-Type: {content_type}")
            lines.append(f"Content-Length: {len(body)}")
        lines.extend(extra or [])
        message = ("\r\n".join(lines) + "\r\n\r\n").encode("iso-8859-1")
        if body is not None:
            message += body
        self.conn.sendall(message)

    def unauthorized(self, cseq: str, uri: str) -> None:
        self.respond(cseq, 401, "Unauthorized", [f"WWW-Authenticate: {challenge_header(self.nonce)}"])

    # ── ffmpeg sender ────────────────────────────────────────────────────
    def stop_sender(self) -> None:
        if self.sender is not None:
            try:
                self.sender.terminate()
                self.sender.wait(timeout=3)
            except Exception:
                try:
                    self.sender.kill()
                except Exception:
                    pass
            self.sender = None

    def start_sender(self) -> None:
        if self.client_port is None:
            return
        self.stop_sender()
        target = f"rtp://{self.client_ip}:{self.client_port}"
        log_path = f"/tmp/opencode/ffmpeg_{self.client_port}.log"
        log = open(log_path, "wb")
        try:
            self.sender = subprocess.Popen(
                [
                    "ffmpeg", "-v", "verbose", "-re", "-stream_loop", "-1", "-i", self.cfg.video,
                    "-an", "-c:v", "copy", "-f", "rtp", "-payload_type", str(PAYLOAD_TYPE),
                    "-pkt_size", "1200", target,
                ],
                stdout=log, stderr=log,
            )
        finally:
            log.close()
        print(f"[cam] PLAY {self.addr[0]} -> {target} (ffmpeg pid {self.sender.pid}, log {log_path})", flush=True)

    # ── main loop ────────────────────────────────────────────────────────
    def serve(self) -> None:
        try:
            while not self.closed:
                parsed = self.read_request()
                if parsed is None:
                    break
                method, uri, headers = parsed
                cseq = headers.get("cseq", "0")
                self.conn.settimeout(None)
                if method == "OPTIONS":
                    self.respond(cseq, 200, "OK", [
                        "Public: OPTIONS, DESCRIBE, SETUP, PLAY, GET_PARAMETER, TEARDOWN",
                    ])
                    continue
                if not verify_digest(method, uri, headers.get("authorization"),
                                     self.cfg.user, self.cfg.password):
                    self.unauthorized(cseq, uri)
                    continue
                if method == "DESCRIBE":
                    body = self.cfg.sdp.encode("utf-8")
                    base = uri.rsplit("/", 1)[0] + "/"
                    self.respond(cseq, 200, "OK", [f"Content-Base: {base}"], body=body,
                                 content_type="application/sdp")
                elif method == "SETUP":
                    match = re.search(r"client_port=(\d+)(?:-(\d+))?", headers.get("transport", ""))
                    if not match:
                        self.respond(cseq, 461, "Unsupported Transport")
                        continue
                    self.client_port = int(match.group(1))
                    self.respond(cseq, 200, "OK", [
                        "Transport: RTP/AVP/UDP;unicast;"
                        f"client_port={self.client_port}-{self.client_port + 1};"
                        "server_port=5004-5005;ssrc=0x1a2b3c4d",
                        f"Session: {self.session_id};timeout=60",
                    ])
                elif method == "PLAY":
                    self.respond(cseq, 200, "OK", [
                        f"Session: {self.session_id};timeout=60",
                        "Range: npt=0.000-",
                    ])
                    self.start_sender()
                elif method == "GET_PARAMETER":
                    self.respond(cseq, 200, "OK", [f"Session: {self.session_id};timeout=60"])
                elif method == "TEARDOWN":
                    self.respond(cseq, 200, "OK", [f"Session: {self.session_id}"])
                    break
                else:
                    self.respond(cseq, 405, "Method Not Allowed")
        except (ConnectionError, OSError):
            pass
        finally:
            self.close()

    def close(self) -> None:
        if self.closed:
            return
        self.closed = True
        self.stop_sender()
        try:
            self.conn.close()
        except OSError:
            pass
        print(f"[cam] disconnected {self.addr}", flush=True)


class Config:
    def __init__(self, args: argparse.Namespace):
        self.video = args.video
        self.user = args.user
        self.password = args.password
        self.host = args.host
        self.port = args.port
        self.path = args.path
        self.sdp = ""


def main() -> int:
    ap = argparse.ArgumentParser(description="RTSP Digest-SHA-256 test camera")
    ap.add_argument("--video", required=True, help="H.264 media file to serve")
    ap.add_argument("--user", default="admin")
    ap.add_argument("--password", default="secret")
    ap.add_argument("--host", default="0.0.0.0")
    ap.add_argument("--port", type=int, default=8554)
    ap.add_argument("--path", default="/test")
    args = ap.parse_args()

    if not os.path.isfile(args.video):
        print(f"video not found: {args.video}", file=sys.stderr)
        return 2

    cfg = Config(args)
    cfg.sdp = build_sdp(cfg.video)
    if "sprop-parameter-sets" not in cfg.sdp:
        print("ffmpeg SDP has no sprop-parameter-sets; is the file H.264?", file=sys.stderr)
        return 2

    listener = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    listener.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    listener.bind((cfg.host, cfg.port))
    listener.listen(8)
    print(f"[cam] rtsp://{cfg.user}:***@{cfg.host}:{cfg.port}{cfg.path}", flush=True)
    print(f"[cam] digest algorithm=SHA-256 only, realm={REALM}", flush=True)

    try:
        while True:
            conn, addr = listener.accept()
            threading.Thread(target=Session(conn, addr, cfg).serve, daemon=True).start()
    except KeyboardInterrupt:
        pass
    finally:
        listener.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
